import {test, expect} from '@playwright/test';
import {adminFirestore} from '../helpers/admin-sdk.mjs';
import {seedPatient, seedPastAppointment} from '../helpers/patient-http.mjs';
import {password} from '../helpers/followup-fixtures.mjs';
let db;
test.beforeEach(async ({context}) => {
  db = adminFirestore.getFirestore(await seedPatient());
  await seedPastAppointment(db, 'confirmada');
  await context.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
});
async function login(page, who, path) {
  await page.goto('/login');
  await page.evaluate(() => localStorage.setItem('psicofound-active-mode', 'patient'));
  await page.getByRole('textbox', {name:'Correo', exact:true}).fill(`${who}@example.test`);
  await page.getByRole('textbox', {name:'Contraseña', exact:true}).fill(password);
  await page.getByRole('button', {name:'Iniciar Sesión', exact:true}).click();
  await expect(page).not.toHaveURL(/\/login/);
  await page.goto(path);
}
test('attendance: professional records, corrects and undoes; patient can read the original and correction', async ({page}, info) => {
  await login(page, 'professional-a', '/psicologo/sesiones');
  const row = page.getByRole('row').filter({hasText:'confirmada'});
  await row.getByRole('button', {name:'Marcar como realizada', exact:true}).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByRole('textbox', {name:'Resumen compartido de la sesión'}).fill('Resumen original de prueba');
  await dialog.getByRole('button', {name:'Marcar realizada', exact:true}).click();
  await expect(dialog).toHaveCount(0);
  const original = (await db.doc('citas/past-open').get()).data();
  expect(original.attendedAt).toBe('2020-01-01T15:00:00.000Z');
  await page.getByRole('row').filter({hasText:'2020-01-01'}).getByRole('button', {name:'Corregir atención', exact:true}).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('textbox', {name:'Hora de atención (Lima)'}).fill('10:20');
  await dialog.getByRole('textbox', {name:'Resumen compartido de la sesión'}).fill('Resumen corregido de prueba');
  await expect(dialog.getByRole('button', {name:'Guardar corrección', exact:true})).toBeDisabled();
  await dialog.getByRole('textbox', {name:'Motivo de la corrección', exact:true}).fill('Corregí la hora y el resumen');
  await dialog.getByRole('button', {name:'Guardar corrección', exact:true}).click();
  await expect(dialog).toHaveCount(0);
  expect((await db.doc('citas/past-open').get()).data().completedAt.toMillis()).toBe(original.completedAt.toMillis());
  await page.goto('/configuracion');
  await page.getByRole('button', {name:'Cerrar sesión', exact:true}).click();
  await expect(page).toHaveURL(/\/login/);
  await login(page, 'patient-b', '/sesiones');
  await page.getByRole('button', {name:'Ver resumen', exact:true}).click();
  dialog = page.getByRole('dialog');
  await expect(dialog).toContainText('Resumen original de prueba');
  await expect(dialog).toContainText('Resumen corregido de prueba');
  await expect(dialog).toContainText('Corregí la hora y el resumen');
  await page.screenshot({path:info.outputPath('attendance-history.png'), fullPage:true});
  await dialog.getByRole('button', {name:'Cerrar', exact:true}).click();
  await page.goto('/configuracion');
  await page.getByRole('button', {name:'Cerrar sesión', exact:true}).click();
  await expect(page).toHaveURL(/\/login/);
  await login(page, 'professional-a', '/psicologo/sesiones');
  await page.getByRole('row').filter({hasText:'2020-01-01'}).getByRole('button', {name:'Deshacer realización', exact:true}).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('textbox', {name:'Motivo de la corrección', exact:true}).fill('Se registró una atención que no ocurrió');
  await dialog.getByRole('checkbox', {name:'Confirmo que la sesión no ocurrió y se marcó realizada por error'}).check();
  await dialog.getByRole('button', {name:'Deshacer realización', exact:true}).click();
  await expect(dialog).toHaveCount(0);
  expect((await db.doc('citas/past-open').get()).data().estado).toBe('confirmada');
  expect((await db.doc('payment_operations/past-open').get()).data().status).toBe('pending');
});
